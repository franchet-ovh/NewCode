//! Own the native editor session without presenting a window for every backend poll.
use super::{
    Host,
    protocol::{Control, Frame, Input},
    registry,
};
use crate::{file_picker::Purpose, logging::Arguments};
use std::{
    path::PathBuf,
    sync::{
        Arc, Mutex,
        atomic::{AtomicBool, Ordering},
        mpsc::{self, Receiver, SyncSender},
    },
    thread::JoinHandle,
    time::{Duration, Instant},
};
use tiny_http::{Request, Server};

const CLIENT: &str = "native-window";
const FRAME_INTERVAL: Duration = Duration::from_nanos(1_000_000_000 / 60);
const MAINTENANCE_INTERVAL: Duration = Duration::from_millis(100);

pub(super) enum Command {
    Input(Input),
    Applied { reset: bool },
    Claim,
    Close(CloseAction),
    SaveSettings,
    DialogResult(Purpose, Option<PathBuf>),
    Http(Request),
    Wake,
}

#[derive(Clone, Copy)]
pub(super) enum CloseAction {
    Check,
    Save,
    Discard,
}

#[derive(Debug, PartialEq)]
pub(super) enum CloseResult {
    Allowed,
    Dirty,
    SaveFailed,
}

pub(super) enum Event {
    Frame(Box<Frame>),
    Close(CloseResult),
    Dialog(Purpose, PathBuf),
    Failed(String),
    Stopped,
}

/// Repaint requests wake the session worker, never the native window. A zero-delay
/// request generated by a polling widget must not turn into an unbounded busy loop.
struct Schedule {
    due: Mutex<Option<Instant>>,
    sender: SyncSender<Command>,
}
impl Schedule {
    fn request(&self, delay: Duration) {
        let Some(due) = Instant::now().checked_add(delay) else {
            return;
        };
        let mut pending = self.due.lock().unwrap();
        if pending.is_none_or(|previous| due < previous) {
            *pending = Some(due);
            let _ = self.sender.try_send(Command::Wake);
        }
    }
    fn deadline(&self, last_render: Instant) -> Option<Instant> {
        self.due
            .lock()
            .unwrap()
            .map(|due| due.max(last_render + FRAME_INTERVAL))
    }
    fn take_due(&self, now: Instant, last_render: Instant) -> bool {
        let mut pending = self.due.lock().unwrap();
        if pending.is_some_and(|due| due.max(last_render + FRAME_INTERVAL) <= now) {
            *pending = None;
            true
        } else {
            false
        }
    }
}

pub(super) struct Worker {
    pub sender: SyncSender<Command>,
    pub incoming: Receiver<Event>,
    pub control: Control,
    stopped: Arc<AtomicBool>,
    thread: Option<JoinHandle<()>>,
}
impl Worker {
    pub fn start(
        args: &Arguments,
        wake_window: impl Fn() + Send + Sync + 'static,
    ) -> Result<Self, String> {
        let server = Server::http("127.0.0.1:0").map_err(|error| error.to_string())?;
        let origin = format!(
            "http://{}",
            server.server_addr().to_ip().ok_or("Invalid listener")?
        );
        let token = registry::random_id().map_err(|error| error.to_string())?;
        let args = args.clone();
        let wake_window: Arc<dyn Fn() + Send + Sync> = Arc::new(wake_window);
        let (sender, commands) = mpsc::sync_channel(64);
        let (events, incoming) = mpsc::channel();
        let (ready, startup) = mpsc::channel();
        let stopped = Arc::new(AtomicBool::new(false));
        let schedule = Arc::new(Schedule {
            due: Mutex::new(None),
            sender: sender.clone(),
        });
        let worker_stopped = stopped.clone();
        let thread = std::thread::Builder::new()
            .name("native-session".into())
            .spawn(move || {
                let notify = |event| {
                    if events.send(event).is_ok() {
                        wake_window();
                    }
                };
                let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
                    let mut host = Host::new(&args, &origin, &token, "native")
                        .map_err(|error| error.to_string())?;
                    let control = host.runtime.connect(CLIENT, false);
                    let repaint = schedule.clone();
                    host.runtime
                        .renderer
                        .set_waker(move |info| repaint.request(info.delay));
                    let dialog_events = events.clone();
                    let dialog_wake = wake_window.clone();
                    // The GUI executes dialogs asynchronously; the session never waits for
                    // the main thread, including while the window is being shut down.
                    host.runtime
                        .renderer
                        .delegate_dialogs(Arc::new(move |purpose, path| {
                            if dialog_events.send(Event::Dialog(purpose, path)).is_ok() {
                                dialog_wake();
                            }
                        }));
                    let _reader =
                        HttpReader::start(server, schedule.sender.clone(), worker_stopped.clone());
                    ready
                        .send(Ok(control))
                        .map_err(|_| "Native window closed".to_string())?;
                    let mut awaiting_frame = false;
                    let mut maintenance = Instant::now();
                    while !worker_stopped.load(Ordering::Acquire) && !host.stop {
                        let deadline = schedule
                            .deadline(host.runtime.last_rendered())
                            .map_or(maintenance, |due| due.min(maintenance));
                        match commands
                            .recv_timeout(deadline.saturating_duration_since(Instant::now()))
                        {
                            Ok(command) => {
                                handle(&mut host, command, &mut awaiting_frame, &notify)?;
                                for command in commands.try_iter().take(63) {
                                    handle(&mut host, command, &mut awaiting_frame, &notify)?;
                                }
                            }
                            Err(mpsc::RecvTimeoutError::Timeout) => {}
                            Err(mpsc::RecvTimeoutError::Disconnected) => break,
                        }
                        host.runtime.keep_alive(CLIENT);
                        if Instant::now() >= maintenance {
                            host.tick();
                            maintenance = Instant::now() + MAINTENANCE_INTERVAL;
                        }
                        if schedule.take_due(Instant::now(), host.runtime.last_rendered()) {
                            host.runtime.refresh();
                        }
                        // Taking a snapshot advances its texture revision and drains one-shot
                        // commands. Never take another until the GUI has applied this one.
                        if !awaiting_frame {
                            if let Some(frame) = host.runtime.snapshot(CLIENT)? {
                                notify(Event::Frame(Box::new(frame)));
                                awaiting_frame = true;
                            }
                        }
                    }
                    Ok::<_, String>(())
                }))
                .unwrap_or_else(|_| Err("Native editor session panicked".into()));
                match result {
                    Ok(()) => notify(Event::Stopped),
                    Err(error) => {
                        let _ = ready.send(Err(error.clone()));
                        notify(Event::Failed(error));
                    }
                }
            })
            .map_err(|error| error.to_string())?;
        let mut worker = Self {
            sender,
            incoming,
            control: Control::default(),
            stopped,
            thread: Some(thread),
        };
        worker.control = startup
            .recv()
            .map_err(|_| "Native editor failed to start".to_string())??;
        Ok(worker)
    }
}
impl Drop for Worker {
    fn drop(&mut self) {
        self.stopped.store(true, Ordering::Release);
        let _ = self.sender.try_send(Command::Wake);
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}

fn handle(
    host: &mut Host,
    command: Command,
    awaiting_frame: &mut bool,
    notify: &impl Fn(Event),
) -> Result<(), String> {
    match command {
        Command::Input(input) => host.runtime.apply_input(CLIENT, input)?,
        Command::Applied { reset } => {
            *awaiting_frame = false;
            if reset {
                host.runtime.reset_viewer(CLIENT);
            }
        }
        Command::Claim => {
            host.runtime.claim(CLIENT);
        }
        Command::Close(action) => {
            let result = match action {
                CloseAction::Check if host.runtime.renderer.dirty() => CloseResult::Dirty,
                CloseAction::Save if !host.runtime.renderer.save_documents() => {
                    CloseResult::SaveFailed
                }
                _ => CloseResult::Allowed,
            };
            notify(Event::Close(result));
        }
        Command::SaveSettings => host.runtime.renderer.save(),
        Command::DialogResult(purpose, path) => host.runtime.renderer.finish_dialog(purpose, path),
        Command::Http(request) => host.handle(request),
        Command::Wake => {}
    }
    Ok(())
}

struct HttpReader {
    stopped: Arc<AtomicBool>,
    thread: Option<JoinHandle<()>>,
}
impl HttpReader {
    fn start(server: Server, sender: SyncSender<Command>, stopped: Arc<AtomicBool>) -> Self {
        let reader_stopped = stopped.clone();
        let thread = std::thread::spawn(move || {
            while !reader_stopped.load(Ordering::Acquire) {
                if let Ok(Some(request)) = server.recv_timeout(MAINTENANCE_INTERVAL) {
                    if let Err(
                        mpsc::TrySendError::Full(Command::Http(request))
                        | mpsc::TrySendError::Disconnected(Command::Http(request)),
                    ) = sender.try_send(Command::Http(request))
                    {
                        super::respond(request, 503, "text/plain", "Editor is busy", false);
                    }
                }
            }
        });
        Self {
            stopped,
            thread: Some(thread),
        }
    }
}
impl Drop for HttpReader {
    fn drop(&mut self) {
        self.stopped.store(true, Ordering::Release);
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}

